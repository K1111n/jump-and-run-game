/**
 * Keyboard input handler
 */
class Keyboard {
     /** @type {boolean} Left key pressed */
     LEFT = false;
    
     /** @type {boolean} Right key pressed */
     RIGHT = false;
     
     /** @type {boolean} Up/Jump key pressed */
     UP = false;
     
     /** @type {boolean} Down key pressed */
     DOWN = false;
     
     /** @type {boolean} Space/Throw key pressed */
     SPACE = false;
}